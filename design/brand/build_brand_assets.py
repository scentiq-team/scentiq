"""Builds the ScentIQ brand assets from the real font outlines (no hand-drawn curves).

Outputs (all committed, so nobody needs to run this to work on the project):
  apps/frontend/public/favicon.svg, favicon.ico, apple-touch-icon.png, og-default.png
  apps/frontend/src/ui/logoPaths.ts   (path data used by the LogoMark component)

Run it only when the logo changes. Needs Python 3 with fontTools, Pillow and playwright
(and a Chromium), for example:  python design/brand/build_brand_assets.py
Set PW_CHROMIUM_EXECUTABLE if Playwright cannot find its browser.
"""

import os
from pathlib import Path

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[2]
FRONTEND = ROOT / "apps" / "frontend"
FONTS = FRONTEND / "node_modules" / "@fontsource"
PUBLIC = FRONTEND / "public"

# Direction A tokens (src/styles/tokens.css)
BG, ACCENT, SIGNAL, MUTED, TEXT = "#0e0c0a", "#c9a45c", "#86a8b6", "#aca392", "#f3ebdd"

font = TTFont(FONTS / "cormorant-garamond" / "files" / "cormorant-garamond-latin-600-normal.woff")
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()


def fmt(value: float) -> str:
    return f"{value:.1f}".rstrip("0").rstrip(".")


def glyph_bounds(char: str):
    pen = BoundsPen(glyphs)
    glyphs[cmap[ord(char)]].draw(pen)
    return pen.bounds  # xmin, ymin, xmax, ymax


def place(char: str, height: float, x_left: float, y_top: float):
    """SVG path of one glyph scaled to `height` (its ink height) with its ink box at (x_left, y_top)."""
    xmin, ymin, xmax, ymax = glyph_bounds(char)
    scale = height / (ymax - ymin)
    pen = SVGPathPen(glyphs, ntos=fmt)
    # Font units go up, SVG goes down, so flip y.
    transform = (scale, 0, 0, -scale, x_left - scale * xmin, y_top + scale * ymax)
    glyphs[cmap[ord(char)]].draw(TransformPen(pen, transform))
    return pen.getCommands(), (xmax - xmin) * scale


def centered(char: str, height: float, cx: float, y_top: float):
    _, width = place(char, height, 0, y_top)
    return place(char, height, cx - width / 2, y_top)[0]


def iq_run(height: float, cx: float, y_top: float, gap: float):
    _, wi = place("I", height, 0, 0)
    _, wq = place("Q", height, 0, 0)
    left = cx - (wi + gap + wq) / 2
    return place("I", height, left, y_top)[0] + place("Q", height, left + wi + gap, y_top)[0]


# --- the mark (512 x 512) ------------------------------------------------------------------
S_FULL = centered("S", 270, 256, 92)
IQ_FULL = iq_run(58, 256, 398, 22)
S_SIMPLE = centered("S", 330, 256, 80)


def svg(body: str, title: str | None = None, size: int | None = None) -> str:
    dims = f' width="{size}" height="{size}"' if size else ""
    label = f"<title>{title}</title>" if title else ""
    role = ' role="img"' if title else ' aria-hidden="true"'
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"{dims}{role}>{label}{body}</svg>'


def frame(radius: int, border: bool) -> str:
    stroke = f' stroke="{ACCENT}" stroke-width="10"' if border else ""
    inset = 8 if border else 0
    return (
        f'<rect x="{inset}" y="{inset}" width="{512 - 2 * inset}" height="{512 - 2 * inset}" '
        f'rx="{radius}" fill="{BG}"{stroke}/>'
    )


FULL_BODY = frame(108, True) + f'<path d="{S_FULL}" fill="{ACCENT}"/><path d="{IQ_FULL}" fill="{SIGNAL}"/>'
FAVICON_BODY = frame(108, True) + f'<path d="{S_SIMPLE}" fill="{ACCENT}"/><circle cx="404" cy="404" r="26" fill="{SIGNAL}"/>'
TOUCH_BODY = frame(0, False) + f'<path d="{S_FULL}" fill="{ACCENT}"/><path d="{IQ_FULL}" fill="{SIGNAL}"/>'

PUBLIC.mkdir(parents=True, exist_ok=True)
(PUBLIC / "favicon.svg").write_text(svg(FAVICON_BODY, "ScentIQ"), encoding="utf-8")

(FRONTEND / "src" / "ui" / "logoPaths.ts").write_text(
    "// Generated by design/brand/build_brand_assets.py from the Cormorant Garamond outlines.\n"
    "// Do not edit by hand. Coordinates are in a 512 x 512 box.\n"
    f"export const MARK_S_PATH = '{S_FULL}';\n"
    f"export const MARK_IQ_PATH = '{IQ_FULL}';\n",
    encoding="utf-8",
)

# --- raster files --------------------------------------------------------------------------
og_html = f"""<!doctype html><meta charset="utf-8"><style>
@font-face {{ font-family: 'Cormorant'; font-weight: 600;
  src: url('{(FONTS / 'cormorant-garamond' / 'files' / 'cormorant-garamond-latin-600-normal.woff2').as_uri()}') }}
@font-face {{ font-family: 'Messiri'; font-weight: 600;
  src: url('{(FONTS / 'el-messiri' / 'files' / 'el-messiri-arabic-600-normal.woff2').as_uri()}') }}
html,body {{ margin:0; width:1200px; height:630px; background:{BG}; }}
body {{ display:flex; flex-direction:column; align-items:center; justify-content:center; gap:22px;
  background: radial-gradient(60% 70% at 50% 35%, rgba(201,164,92,.16), transparent 70%), {BG}; }}
.mark {{ width:190px; height:190px; }}
.word {{ font: 600 104px/1 'Cormorant', serif; letter-spacing:.04em; color:{TEXT}; direction:ltr; }}
.word b {{ color:{ACCENT}; font-weight:600; }}
.tag {{ display:flex; gap:28px; align-items:center; color:{MUTED}; }}
.ar {{ font: 600 46px/1 'Messiri', serif; direction:rtl; }}
.dot {{ width:8px; height:8px; border-radius:50%; background:{SIGNAL}; }}
.en {{ font: 600 38px/1 'Cormorant', serif; letter-spacing:.12em; text-transform:uppercase; }}
</style>
<div class="mark">{svg(FULL_BODY)}</div>
<div class="word">Scent<b>IQ</b></div>
<div class="tag"><span class="ar">عطور فاخرة</span><span class="dot"></span><span class="en">Luxury fragrance</span></div>"""

tmp = ROOT / "design" / "brand" / ".og.html"
tmp.write_text(og_html, encoding="utf-8")

executable = os.environ.get("PW_CHROMIUM_EXECUTABLE")
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=executable) if executable else p.chromium.launch()
    page = browser.new_page(viewport={"width": 1200, "height": 630})
    page.goto(tmp.as_uri())
    page.evaluate("document.fonts.ready")
    page.wait_for_timeout(300)
    page.screenshot(path=str(PUBLIC / "og-default.png"))

    icon = browser.new_page(viewport={"width": 256, "height": 256})
    icon.set_content(f'<body style="margin:0;background:transparent">{svg(FAVICON_BODY, size=256)}</body>')
    icon.screenshot(path=str(ROOT / "design" / "brand" / ".favicon-256.png"), omit_background=True)

    touch = browser.new_page(viewport={"width": 180, "height": 180})
    touch.set_content(f'<body style="margin:0">{svg(TOUCH_BODY, size=180)}</body>')
    touch.screenshot(path=str(PUBLIC / "apple-touch-icon.png"))
    browser.close()

base = Image.open(ROOT / "design" / "brand" / ".favicon-256.png").convert("RGBA")
base.save(PUBLIC / "favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
tmp.unlink()
(ROOT / "design" / "brand" / ".favicon-256.png").unlink()
print("brand assets written to", PUBLIC)
